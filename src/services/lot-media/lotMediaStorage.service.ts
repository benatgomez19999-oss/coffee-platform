//////////////////////////////////////////////////////
// ERROR TYPE
//////////////////////////////////////////////////////

export type LotMediaStorageErrorCode =
  | "STORAGE_NOT_CONFIGURED"
  | "MEDIA_UPLOAD_INVALID"
  | "MEDIA_UPLOAD_FORBIDDEN"
  | "MEDIA_UPLOAD_SIGNING_FAILED"
  | "MEDIA_READ_SIGNING_FAILED"
  | "OWNER_NOT_FOUND"

export class LotMediaStorageError extends Error {
  code: LotMediaStorageErrorCode
  status: number
  details?: Record<string, unknown>

  constructor(
    code: LotMediaStorageErrorCode,
    message: string,
    opts?: { status?: number; details?: Record<string, unknown> },
  ) {
    super(message)
    this.code = code
    this.name = "LotMediaStorageError"
    this.status =
      opts?.status ??
      (code === "STORAGE_NOT_CONFIGURED"
        ? 503
        : code === "MEDIA_UPLOAD_FORBIDDEN"
          ? 403
          : code === "OWNER_NOT_FOUND"
            ? 404
            : code === "MEDIA_UPLOAD_INVALID"
              ? 400
              : 500)
    if (opts?.details) this.details = opts.details
  }
}

//////////////////////////////////////////////////////
// LAZY CLIENT
//
// We resolve env at call time (not module load) so a
// later sprint can ship a different config / a feature
// flag without restarting tests. The client is cached
// once instantiated.
//
// BUYER-PROOF-1: env now carries the PUBLIC + PRIVATE
// bucket pair. We fall back to the legacy single-bucket
// env when set so STORAGE-MEDIA-1 deployments keep
// signing public uploads.
//////////////////////////////////////////////////////

type StorageEnv = {
  url: string
  serviceRoleKey: string
  buckets: LotMediaBucketConfig
}

let cachedClient: SupabaseClient | null = null
let cachedEnv: StorageEnv | null = null

function readStorageEnv(): StorageEnv | null {
  const url =
    process.env.NEXT_PUBLIC_SUPABASE_URL ||
    process.env.SUPABASE_URL ||
    ""
  const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY || ""
  // Legacy single-bucket env (STORAGE-MEDIA-1). When the new
  // *_PUBLIC_BUCKET var is not set we treat the legacy var as
  // the public bucket so existing deploys keep working.
  const legacyBucket = process.env.SUPABASE_LOT_MEDIA_BUCKET || ""
  const publicBucket =
    process.env.SUPABASE_LOT_MEDIA_PUBLIC_BUCKET ||
    legacyBucket ||
    LOT_MEDIA_PUBLIC_BUCKET_DEFAULT
  const privateBucket =
    process.env.SUPABASE_LOT_MEDIA_PRIVATE_BUCKET ||
    LOT_MEDIA_PRIVATE_BUCKET_DEFAULT
  if (!url || !serviceRoleKey) return null
  return {
    url,
    serviceRoleKey,
    buckets: { publicBucket, privateBucket },
  }
}

function getSupabaseClient(): { client: SupabaseClient; env: StorageEnv } {
  const env = readStorageEnv()
  if (!env) {
    throw new LotMediaStorageError(
      "STORAGE_NOT_CONFIGURED",
      "Image uploads aren't configured on this environment yet. You can still paste an image URL.",
    )
  }
  if (cachedClient && cachedEnv && cachedEnv.url === env.url) {
    return { client: cachedClient, env }
  }
  cachedClient = createClient(env.url, env.serviceRoleKey, {
    auth: {
      // Service-role client; never refresh sessions.
      autoRefreshToken: false,
      persistSession: false,
    },
  })
  cachedEnv = env
  return { client: cachedClient, env }
}

// Exported for the proof-media route layer so it can
// surface a clean 503 without trying to sign anything.
export function isLotMediaStorageConfigured(): boolean {
  return readStorageEnv() !== null
}

// Surfaced so callers (proof endpoint) can confirm the
// configured private bucket matches references stored
// in the database before signing.
export function getLotMediaBucketConfig(): LotMediaBucketConfig {
  return getSupabaseClient().env.buckets
}

