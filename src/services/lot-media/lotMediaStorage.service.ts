//////////////////////////////////////////////////////
// OWNERSHIP CHECKS
//
// Mirror the contract used by lotMedia.service —
// producer can only sign uploads for their own farms /
// lots; partner / admin bypass. We re-run the check
// here (vs. trusting the route) so the storage service
// is safe to call from anywhere.
//////////////////////////////////////////////////////

async function ensureFarmOwnership(
  farmId: string,
  actor: LotMediaActor,
): Promise<void> {
  const farm = await prisma.farm.findUnique({
    where: { id: farmId },
    select: { id: true, producer: { select: { userId: true } } },
  })
  if (!farm) {
    throw new LotMediaStorageError("OWNER_NOT_FOUND", "Farm not found.")
  }
  if (actor.role === "PRODUCER" && farm.producer?.userId !== actor.userId) {
    throw new LotMediaStorageError(
      "MEDIA_UPLOAD_FORBIDDEN",
      "You can only upload media on farms you own.",
    )
  }
}

async function ensureLotOwnership(
  greenLotId: string,
  actor: LotMediaActor,
): Promise<void> {
  const lot = await prisma.greenLot.findUnique({
    where: { id: greenLotId },
    select: {
      id: true,
      farm: { select: { producer: { select: { userId: true } } } },
    },
  })
  if (!lot) {
    throw new LotMediaStorageError("OWNER_NOT_FOUND", "Green lot not found.")
  }
  if (
    actor.role === "PRODUCER" &&
    lot.farm?.producer?.userId !== actor.userId
  ) {
    throw new LotMediaStorageError(
      "MEDIA_UPLOAD_FORBIDDEN",
      "You can only upload media on lots you own.",
    )
  }
}

//////////////////////////////////////////////////////
// CORE: createLotMediaSignedUpload
//
// 1. Validate the upload request via the pure helper.
// 2. Confirm the actor can write to the owner.
// 3. Resolve bucket from visibility (PUBLIC_MARKET vs
//    BUYER_PRIVATE / INTERNAL_ONLY).
// 4. Build a safe storage path.
// 5. Ask Supabase Storage for a signed upload URL.
// 6. Return the URL + token + storage reference. The
//    publicUrl is set only for PUBLIC uploads; private
//    rows persist the storageReference instead.
//
// We deliberately do NOT create the FarmMedia /
// GreenLotMedia row here. The browser POSTs to the
// existing create endpoint with the appropriate `url`
// (publicUrl or storageReference) after the upload
// completes, so the same single-primary transaction +
// ownership checks fire.
//////////////////////////////////////////////////////

export type CreateLotMediaSignedUploadInput = {
  actor: LotMediaActor
  target: LotMediaUploadTarget
  ownerId: string
  body: LotMediaUploadRequestInput
}

export async function createLotMediaSignedUpload(
  input: CreateLotMediaSignedUploadInput,
): Promise<LotMediaSignedUploadResponse> {

  // ─── VALIDATE ─────────────────────────────────────
  const validation = validateLotMediaUploadRequest(input.body)
  if (!validation.ok) {
    throw new LotMediaStorageError(
      "MEDIA_UPLOAD_INVALID",
      validation.error.message,
      { details: { code: validation.error.code } },
    )
  }
  const req = validation.input

  // ─── OWNERSHIP ────────────────────────────────────
  if (input.target === "FARM") {
    await ensureFarmOwnership(input.ownerId, input.actor)
  } else {
    await ensureLotOwnership(input.ownerId, input.actor)
  }

  // ─── ENV / CLIENT ─────────────────────────────────
  const { client, env } = getSupabaseClient()

  // ─── BUCKET RESOLUTION ────────────────────────────
  const bucketResolution = resolveLotMediaBucketForVisibility(
    req.visibility,
    env.buckets,
  )
  const targetBucket = bucketResolution.bucket

  // ─── STORAGE PATH ─────────────────────────────────
  const storagePath = buildLotMediaStoragePath({
    target: input.target,
    ownerId: input.ownerId,
    role: req.role,
    contentType: req.contentType,
    uuid: randomUUID(),
  })

  // ─── SIGN UPLOAD ──────────────────────────────────
  let signedUrl: string
  let token: string | undefined
  try {
    const { data, error } = await client.storage
      .from(targetBucket)
      .createSignedUploadUrl(storagePath)
    if (error || !data?.signedUrl) {
      throw new LotMediaStorageError(
        "MEDIA_UPLOAD_SIGNING_FAILED",
        "We couldn't prepare the upload. Please try again in a moment.",
        { details: error ? { supabaseError: error.message } : undefined },
      )
    }
    signedUrl = data.signedUrl
    token = (data as { token?: string }).token
  } catch (err) {
    if (err instanceof LotMediaStorageError) throw err
    throw new LotMediaStorageError(
      "MEDIA_UPLOAD_SIGNING_FAILED",
      "We couldn't prepare the upload.",
      { details: { error: err instanceof Error ? err.message : String(err) } },
    )
  }

  // ─── REFERENCE + PUBLIC URL ───────────────────────
  const storageReference = buildLotMediaStorageReference({
    bucket: targetBucket,
    storagePath,
  })

  // Public URL only for PUBLIC bucket uploads. Private
  // rows must be read through createLotMediaSignedReadUrl.
  let publicUrl: string | null = null
  if (bucketResolution.kind === "PUBLIC") {
    const { data: publicData } = client.storage
      .from(targetBucket)
      .getPublicUrl(storagePath)
    publicUrl = publicData?.publicUrl ?? null
  }

  return {
    uploadUrl: signedUrl,
    token,
    method: "PUT",
    bucket: targetBucket,
    bucketKind: bucketResolution.kind,
    storagePath,
    storageReference,
    publicUrl,
    expiresInSeconds: LOT_MEDIA_SIGNED_URL_EXPIRY_SECONDS,
    mediaDefaults: {
      role: req.role,
      source: req.source,
      visibility: req.visibility,
    },
  }
}

//////////////////////////////////////////////////////
// CORE: createLotMediaSignedReadUrl
//
// Signs a short-lived read URL for a private storage
// reference. Used exclusively by the proof-media
// endpoint after it has confirmed the caller is
// authorised to view the underlying contract/lot.
//
// Callers MUST run their own audience filter first —
// this helper trusts its input and only handles the
// signing mechanics.
//////////////////////////////////////////////////////

export type CreateLotMediaSignedReadUrlInput = {
  bucket: string
  storagePath: string
  expiresInSeconds?: number
}

export type LotMediaSignedReadUrlResult = {
  bucket: string
  storagePath: string
  signedUrl: string
  expiresInSeconds: number
}

export async function createLotMediaSignedReadUrl(
  input: CreateLotMediaSignedReadUrlInput,
): Promise<LotMediaSignedReadUrlResult> {
  const { client } = getSupabaseClient()
  const expiresIn =
    typeof input.expiresInSeconds === "number" &&
    Number.isFinite(input.expiresInSeconds) &&
    input.expiresInSeconds > 0
      ? Math.floor(input.expiresInSeconds)
      : LOT_MEDIA_SIGNED_READ_URL_EXPIRY_SECONDS

  try {
    const { data, error } = await client.storage
      .from(input.bucket)
      .createSignedUrl(input.storagePath, expiresIn)
    if (error || !data?.signedUrl) {
      throw new LotMediaStorageError(
        "MEDIA_READ_SIGNING_FAILED",
        "We couldn't prepare the proof image for viewing.",
        {
          details: {
            bucket: input.bucket,
            supabaseError: error?.message,
          },
        },
      )
    }
    return {
      bucket: input.bucket,
      storagePath: input.storagePath,
      signedUrl: data.signedUrl,
      expiresInSeconds: expiresIn,
    }
  } catch (err) {
    if (err instanceof LotMediaStorageError) throw err
    throw new LotMediaStorageError(
      "MEDIA_READ_SIGNING_FAILED",
      "We couldn't prepare the proof image for viewing.",
      { details: { error: err instanceof Error ? err.message : String(err) } },
    )
  }
}

