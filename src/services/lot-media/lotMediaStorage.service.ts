//////////////////////////////////////////////////////
// 🪣 LOT MEDIA STORAGE — SUPABASE SERVICE
// (STORAGE-MEDIA-1 + BUYER-PROOF-1)
//
// Server-side bridge between the upload-url routes and
// Supabase Storage. Lazy: the Supabase client is only
// instantiated when the env is configured. When the
// service-role key is missing, the helper surfaces a
// clear `STORAGE_NOT_CONFIGURED` error so the route
// can return 503 and the producer UI can keep the
// URL-paste fallback alive.
//
// BUYER-PROOF-1 — two-bucket model:
//   public bucket  → PUBLIC_MARKET media (rendered as <img>)
//   private bucket → BUYER_PRIVATE + INTERNAL_ONLY media
//                    (rendered only after a signed read URL
//                    is generated by the proof endpoint).
// The pure helper resolves bucket-kind from visibility; the
// service owns the env reads + signing.
//
// ⚠️ NEVER expose Supabase env keys to the browser.
// The service-role key is server-only.
//////////////////////////////////////////////////////

